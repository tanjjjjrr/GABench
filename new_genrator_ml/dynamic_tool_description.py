class DynamicToolDescriptionGenerator:
    """
    Coordinate graph sampling, xxx generation, and fallback registration.
    
    Call run() during asynchronous step0 preprocessing. The resulting dictionary can replace the hard-coded tool-description mapping.
    
    Parameters
    ----------
    xxx_provider : xxx
        Configured asynchronous xxx provider.
    loader : BaseGraphLoader or None
        Loaded graph data. None activates the fallback path.
    tool_names : list[str]
        Tools requiring dynamic descriptions.
    fallback_descriptions : dict[str, str]
        Descriptions used when xxx generation fails.
    global_description : str
        Context used for non-text graphs.
    sample_seed : int
        Random seed used by GraphContextSampler.
    max_retries : int
        Maximum number of xxx attempts.
    """

    def __init__(
        self,
        xxx_provider,
        tool_names: List[str],
        loader=None,
        fallback_descriptions: Optional[Dict[str, str]] = None,
        global_description: str = "",
        sample_seed: Optional[int] = None,
        max_retries: int = 3,
        walk_depth: int = 5,
        graph_type: str = "citation",
    ) -> None:
        self.xxx = xxx_provider
        self.tool_names = tool_names
        self.loader = loader
        self.fallback_descriptions = fallback_descriptions or {}
        self.global_description = global_description
        self.sample_seed = sample_seed
        self.max_retries = max_retries
        self.walk_depth = walk_depth
        self.graph_type = graph_type

    async def run(self) -> Dict[str, str]:
        """
        Run the complete dynamic-description workflow.
        
        The workflow samples graph context, falls back to global context when necessary, generates placeholder-aware descriptions with the xxx, and uses fallback_descriptions when generation fails.
        
        Returns
        -------
        dict[str, str]
            Mapping from tool names to dynamic or fallback descriptions.
        """
        # ── Step 1: Sample graph context ─────────────────────────────────────────
        graph_context: Optional[Dict[str, Any]] = None

        if self.loader is not None and self.graph_type:
            logger.info("[DynamicToolDesc] Sampling graph context...")
            sampler = GraphContextSampler(
                loader=self.loader,
                max_sample_nodes=50,
                max_depth=self.walk_depth,
                seed=self.sample_seed,
                graph_type=self.graph_type,
                global_description=self.global_description,
            )
            graph_context = sampler.sample()

            if graph_context is None:
                logger.warning("[DynamicToolDesc] Graph sampling failed; trying the fallback interface")
            else:
                logger.info("[DynamicToolDesc] Sampling succeeded; generating a high-level semantic summary...")
                summary_pipe = xxx(self.xxx)
                semantic_summary = await summary_pipe.generate(graph_context)
                graph_context["subgraph_summary"] = semantic_summary
                
                if not graph_context.get("has_text"):
                    logger.info(
                        "[DynamicToolDesc] Graph nodes have no text attributes; building context from the global description"
                    )
                    # Merge: append the global description to the empty-node text block
                    if self.global_description:
                        if not any("[Global Graph Description]" in text for text in graph_context["node_texts"]):
                            graph_context["node_texts"].insert(
                                0, f"[Global Graph Description] {self.global_description}"
                            )
                        if not graph_context["subgraph_summary"].startswith(self.global_description):
                            graph_context["subgraph_summary"] = (
                                self.global_description + "\n\n" +
                                graph_context.get("subgraph_summary", "")
                            )

        # ── Fallback (Task 4): when no loader is available or sampling fails ──────
        if graph_context is None:
            logger.info("[DynamicToolDesc] Using FallbackInterface to build global context")
            fallback = FallbackInterface(self.global_description)
            graph_context = fallback.build_context()

            if not self.global_description:
                logger.warning(
                    "[DynamicToolDesc] No graph context or global description is available; using hard-coded descriptions"
                )
                return dict(self.fallback_descriptions), {}

        # ── Step 2: Dynamic xxx generation (Tasks 2 + 3) ─────────────────────────
        logger.info("[DynamicToolDesc] Calling the xxx to generate fuzzy tool descriptions...")
        pipeline = xxx(
            xxx_provider=self.xxx,
            tool_names=self.tool_names,
            max_retries=self.max_retries,
        )
        dynamic_descs = await pipeline.generate(graph_context)

        # ── Step 3: Backward-compatible fallback (graceful degradation) ──────────
        if dynamic_descs is None:
            logger.warning(
                "[DynamicToolDesc] xxx generation failed; falling back to hard-coded descriptions"
            )
            merged = dict(self.fallback_descriptions)
        else:
            merged = dict(self.fallback_descriptions)
            merged.update(dynamic_descs)
            
        # ── Step 4: Generate dynamic node strategies (new) ───────────────────────
        logger.info("[DynamicToolDesc] Calling the xxx to generate dynamic node strategies...")
        node_pipeline = xxx(self.xxx, max_retries=self.max_retries)
        node_strategies = await node_pipeline.generate(graph_context)
        if not node_strategies:
            logger.warning("[DynamicToolDesc] Node-strategy generation failed; using an empty dictionary")
            node_strategies = {}

        logger.info(
            f"[DynamicToolDesc] Completed: {len(merged)} dynamic descriptions and "
            f"{len(node_strategies)} node strategies"
        )
        return merged, node_strategies

    def render_description_for_tool(
        self,
        tool_name: str,
        descriptions: Dict[str, str],
        node1_desc: str = "",
        node2_desc: str = "",
    ) -> str:
        """
        Replace node placeholders in a tool description with actual node descriptions.
        
        Parameters
        ----------
        tool_name : str
            Tool name.
        descriptions : dict[str, str]
            Dynamic description mapping returned by run().
        node1_desc : str
            Natural-language description of the first node.
        node2_desc : str
            Natural-language description of the second node.
        
        Returns
        -------
        str
            Tool description containing the actual node descriptions.
        """
        desc = descriptions.get(tool_name, "")
        if node1_desc:
            desc = desc.replace("{node1_placeholder}", node1_desc)
        if node2_desc:
            desc = desc.replace("{node2_placeholder}", node2_desc)
        return desc

    def render_full_description_block(
        self,
        descriptions: Dict[str, str],
        node1_desc: str = "",
        node2_desc: str = "",
    ) -> str:
        """Render all tool descriptions as a formatted block for prompt injection, replacing node placeholders at the same time."""
        lines = ["Below are the available graph analysis tools:\n"]
        for i, tool_name in enumerate(self.tool_names, start=1):
            desc = self.render_description_for_tool(
                tool_name, descriptions, node1_desc, node2_desc
            )
            if desc:
                lines.append(f"{i:2d}. {tool_name}\n    → {desc}\n")
        return "\n".join(lines)
