    from xxx import Asyncxxxxxx, Asyncxxx

    provider_type = os.getenv("xxx_PROVIDER_TYPE", "xxx").lower()
    model_name = os.getenv("xxx_MODEL_NAME", "xxx")

    if provider_type == "xxx":
        api_key = os.getenv("xxx_API_KEY")
        base_url = os.getenv("xxx_BASE_URL", "xxx")
        if not api_key:
            logger.error("xxx_PROVIDER_TYPE is xxx, but xxx_API_KEY is not set")
            sys.exit(1)
        client = Asyncxxx(base_url=base_url, api_key=api_key)
        xxx = xxx(client, model_name, "xxx")
    else:
        endpoint = os.getenv("xxx_xxx_ENDPOINT")
        api_key = os.getenv("xxx_xxx_API_KEY")
        api_version = os.getenv("xxx_API_VERSION", "2024-12-01-preview")
        if not endpoint or not api_key:
            logger.error("xxx_PROVIDER_TYPE is xxx, but the required environment variables are not set")
            sys.exit(1)
        client = Asyncxxxxxx(xxx_endpoint=endpoint, api_key=api_key, api_version=api_version)
        xxx = xxx(client, model_name, "xxx")

    return xxx, model_name


