class FallbackInterface:
    """
    Provide fallback context for graphs without raw_text node attributes.
    
    When textual attributes are unavailable or graph sampling fails, a global graph description can be supplied directly instead of sampled context.
    
    Parameters
    ----------
    global_description : str
        User-provided or domain-configured description of the complete graph.
    """

    def __init__(self, global_description: str = "") -> None:
        self.global_description = global_description

    def build_context(self) -> Dict[str, Any]:
        """Build a context dictionary compatible with GraphContextSampler.sample(), using the global description instead of sampled text."""
        return {
            "node_texts": [],
            "edge_texts": [],
            "subgraph_summary": self.global_description,
            "has_text": bool(self.global_description),
            "num_nodes": 0,
            "num_edges": 0,
        }


