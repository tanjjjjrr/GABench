def _classify_tool(tool_name: str) -> str:
    """Classify a tool as two_node, one_node, or full_graph."""
    if tool_name in _TWO_NODE_TOOLS:
        return "two_node"
    if tool_name in _ONE_NODE_TOOLS:
        return "one_node"
    return "full_graph"


def _build_prompt(
    task: Dict,
    dynamic_descriptions: Dict[str, str],
    real_world_scenarios: List[str],
    use_text_only: bool = False,
    enable_ml: bool = True,
    node_cls_desc: str = "",
    graph_cls_desc: str = "",
) -> str:
    """
    Build the step2 xxx prompt according to new_instruct.md.
    
    The prompt exposes only fuzzy tool descriptions, preserves the tool order selected by step1, adds real-world scenario context, and embeds node-assignment rules. When dynamic descriptions are unavailable, it falls back to the original domain_config prompt.
    """
    selected_tools: List[str] = task.get("selected_tools", [])
    node1_desc: str = task["anchor_nodes"]["node1_desc"]
    node2_desc: str = task["anchor_nodes"]["node2_desc"]
    domain: str = task.get("domain", "citation")

    if use_text_only:
        if " - " in node1_desc:
            node1_desc = node1_desc.split(" - ", 1)[1]
        if " - " in node2_desc:
            node2_desc = node2_desc.split(" - ", 1)[1]
        node_rule = '8. **Node Identification:** Seamlessly integrate the provided text descriptions of the entities directly into the narrative.'
    else:
        node_rule = '8. **Node Identification:** Identify the entities by explicitly stating their numerical Node ID (e.g., "the entity with Node ID 123"). You may also include their text if helpful, but the Node ID MUST be clearly stated.'



    # ── Backward-compatible path: use the original domain prompt without dynamic descriptions ──
    if not dynamic_descriptions:
        logger.info("  dynamic_descriptions is empty; using the original domain_config prompt (fallback)")
        config = DOMAIN_CONFIGS.get(domain, DOMAIN_CONFIGS["citation"])
        prompt_template = config["prompt"] + "\n\n**CRITICAL NEW RULE**:\n" + node_rule

        task_semantics = task.get("task_semantics", [])
        semantics_text = "\n".join(
            [f"- Objective {idx+1}: {s['semantic']}"
             for idx, s in enumerate(task_semantics)]
        )
        return prompt_template.format(
            num_tools=len(task_semantics),
            node1_desc=node1_desc,
            node2_desc=node2_desc,
            dataset_name=task["dataset_name"],
            semantics_text=semantics_text
        )

    # ── New path: build a structured prompt from dynamic descriptions ─────────────

    # 1. Real-world scenarios block
    if real_world_scenarios:
        scenario_lines = [
            f"  [{i+1}] {s}" for i, s in enumerate(real_world_scenarios[:8])
        ]
        scenarios_block = "\n".join(scenario_lines)
    else:
        # Use the domain's default description when no scenarios are available
        config = DOMAIN_CONFIGS.get(domain, DOMAIN_CONFIGS["citation"])
        dataset_name = task.get("dataset_name", config["default_dataset_name"])
        scenarios_block = f"  [1] General analytical investigation on the {dataset_name}."

    # 2. Analysis-steps block: show fuzzy descriptions in selected_tools order without tool names
    step_lines = []
    for i, tool_name in enumerate(selected_tools, start=1):
        node_type = _classify_tool(tool_name)
        
        # Allow users to customize the semantics of classification tasks
        if tool_name == "structural_node_embedding_classification" and node_cls_desc:
            fuzzy_desc = node_cls_desc
        elif tool_name == "structural_graph_embedding_classification" and graph_cls_desc:
            fuzzy_desc = graph_cls_desc
        else:
            # Prefer task_semantics (including specific edge removals added dynamically by step1)
            task_semantics_list = task.get("task_semantics", [])
            sem_entry = next(
                (s for s in task_semantics_list if s.get("tool") == tool_name), None
            )
            if sem_entry and sem_entry.get("semantic"):
                fuzzy_desc = sem_entry["semantic"]
            else:
                fuzzy_desc = dynamic_descriptions.get(tool_name, "")

        # Replace placeholders with actual node descriptions
        if fuzzy_desc:
            fuzzy_desc = (
                fuzzy_desc
                .replace("{node1_placeholder}", node1_desc)
                .replace("{node2_placeholder}", node2_desc)
            )
        else:
            fuzzy_desc = f"Analytical step {i}"

        # Add node-type notes to help the xxx understand this step's node requirements
        if node_type == "two_node":
            node_hint = f" [Applied between {node1_desc} → {node2_desc}]"
        elif node_type == "one_node":
            node_hint = f" [Focused on: {node1_desc}]"
        else:
            node_hint = " [Whole-graph analysis]"

        step_lines.append(f"  - {fuzzy_desc}{node_hint}")

    steps_block = "\n".join(step_lines)

    return _QUESTION_PROMPT_TEMPLATE.format(
        scenarios_block=scenarios_block,
        steps_block=steps_block,
        node1_desc=node1_desc,
        node2_desc=node2_desc,
        node_identification_rule=node_rule,
    )


# ─────────────────────────────────────────────────────────────────────────────
# Main flow
# ─────────────────────────────────────────────────────────────────────────────

async def main():
    args = build_parser().parse_args()

    with open(args.input, "r", encoding="utf-8") as f:
        data = json.load(f)

    intermediate_tasks = data.get("intermediate_tasks", [])
    if not intermediate_tasks:
        logger.error("No intermediate tasks found in input file.")
        return

    xxx, model_name = _init_xxx()
    final_tasks = []

    # ── Load the step0 cache (dynamic descriptions + real-world scenarios) ─────
    step0_cache = _load_step0_cache(args.metrics_cache)
    dynamic_descriptions: Dict[str, str] = step0_cache["dynamic_tool_descriptions"]
    real_world_scenarios: List[str] = step0_cache["real_world_scenarios"]
    tpg_graphs_index: Dict[str, dict] = step0_cache.get("tpg_graphs_index", {})

    # Automatically detect TPG mode by checking whether tasks contain graph_idx
    is_tpg = any("graph_idx" in t for t in intermediate_tasks)
    if is_tpg:
        logger.info("[Step2] Detected TPG mode; using per-graph fuzzy descriptions and the molecular-graph question template.")

    start_time = datetime.now()

    for i, t in enumerate(intermediate_tasks):
        logger.info(f"Generating question for task {i+1}/{len(intermediate_tasks)}")
        logger.info(f"  Tools (in order): {t.get('selected_tools', [])}")
        logger.info(f"  Node1: {t['anchor_nodes']['node1_desc']}")
        logger.info(f"  Node2: {t['anchor_nodes']['node2_desc']}")

        import random
        if args.graph_format == "PG":
            use_text_only = False
        else:
            use_text_only = random.choice([True, False])
        logger.info(f"  Mechanism: {'Pure Text (No ID)' if use_text_only else 'Node ID'}")

        # Choose the prompt-building method based on the mode
        if is_tpg:
            graph_idx = t.get("graph_idx", 0)
            graph_cache = tpg_graphs_index.get(str(graph_idx), {})
            per_graph_descs = graph_cache.get("dynamic_tool_descriptions", {})
            prompt = _build_tpg_prompt(t, per_graph_descs, real_world_scenarios, use_text_only, args.enable_ml, args.node_cls_desc, args.graph_cls_desc)
            cur_system_prompt = _TPG_SYSTEM_PROMPT
        else:
            prompt = _build_prompt(t, dynamic_descriptions, real_world_scenarios, use_text_only, args.enable_ml, args.node_cls_desc, args.graph_cls_desc)
            cur_system_prompt = _SYSTEM_PROMPT

        question = None
        for attempt in range(1, args.max_retries + 1):
            try:
                response = await xxx.get_completion(
                    system_prompt=cur_system_prompt,
                    user_prompt=prompt,
                    max_tokens=2000,
                )
                question = response.strip()
                if question:
                    break
            except Exception as e:
                logger.warning(f"  xxx attempt {attempt} failed: {e}")

        if not question:
            logger.error(f"Failed to generate question for task {i+1}")
            continue

        # When perturbation is involved, append the hard-coded removed edges to the question
        if "simulate_edge_perturbation" in t.get("selected_tools", []):
            removed_edges = t.get("ground_truth", {}).get("simulate_edge_perturbation", {}).get("removed_edges", [])
            if removed_edges:
                edge_strs = [f"({u}, {v})" for u, v in removed_edges]
                question += f"\n\nremove edges: [{', '.join(edge_strs)}]"

        # Assemble the complete Benchmark item
        task_dict = {
            "id": f"task_{i+1:04d}",
            "dataset": t["dataset_name"],
            "required_tools": t["selected_tools"],   # Tool order is the analysis order
            "question": question,
            "anchor_nodes": t["anchor_nodes"],
            "ground_truth": t["ground_truth"],
            "evaluation_metric": "exact_match_or_json_check"
        }
        
        # Add a memory tag when perturbation-related tools are involved
        if any("perturb" in tool.lower() for tool in t.get("selected_tools", [])):
            task_dict["tags"] = ["memory"]

        final_tasks.append(task_dict)

    duration = datetime.now() - start_time

    output_data = {
        "generation_info": {
            "pipeline": "GraphAgentBench (Dynamic Fuzzy Description Mode)",
            "timestamp": datetime.now().isoformat(),
            "input_file": args.input,
            "metrics_cache": args.metrics_cache,
            "num_tasks_generated": len(final_tasks),
            "generation_model": model_name,
            "duration_str": str(duration),
            "used_dynamic_descriptions": bool(dynamic_descriptions),
            "num_real_world_scenarios": len(real_world_scenarios),
        },
        "ground_truth_schema": {
            "description": "Each tool mapped to its direct numerical or path result execution on the graph."
        },
        "tasks": final_tasks
    }

    with open(args.output, "w", encoding="utf-8") as f:
        json.dump(output_data, f, indent=2, ensure_ascii=False)

    logger.info(f"Done! Generated {len(final_tasks)} tasks. Saved to {args.output}")


if __name__ == "__main__":
    asyncio.run(main())
