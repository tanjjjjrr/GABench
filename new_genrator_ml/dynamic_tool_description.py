#!/usr/bin/env python3
"""
Dynamic Tool Description Generator
==================================

Implements the dynamic, domain-adaptive fuzzy tool-description mechanism defined in new_instruct.md.

The module replaces descriptions previously hard-coded in task generators with descriptions generated by an xxx from sampled graph context.

Core components
---------------
GraphContextSampler
    Samples representative graph context and extracts readable node and edge text.
xxx
    Generates domain-adaptive fuzzy tool descriptions.
ParameterizedDescriptions
    Ensures generated descriptions contain required node placeholders.
FallbackInterface
    Provides context for graphs without textual node attributes.
DynamicToolDescriptionGenerator
    Coordinates sampling, xxx generation, validation, and fallback behavior.

Design constraints
------------------
- Sampling, xxx generation, and tool registration remain decoupled.
- All xxx operations are asynchronous and should run during step0 preprocessing.
- The xxx must return a JSON mapping from tool names to placeholder-aware descriptions.
- Failures and timeouts degrade gracefully to hard-coded fallback descriptions.
"""

from __future__ import annotations

import asyncio
import json
import logging
import random
import re
from typing import Any, Dict, List, Optional, Tuple

logger = logging.getLogger(__name__)

# ─────────────────────────────────────────────────────────────────────────────
# Task 1: GraphContextSampler — dynamic graph sampling and context extraction
# ─────────────────────────────────────────────────────────────────────────────

class GraphContextSampler:
    """
    Sample a local subgraph from a BaseGraphLoader instance and serialize node and edge context for the xxx.
    
    Parameters
    ----------
    loader : BaseGraphLoader
        Loader containing the graph data.
    max_sample_nodes : int
        Maximum number of sampled nodes, including seeds.
    max_depth : int
        Maximum traversal depth.
    seed : int
        Random seed.
    """

    def __init__(
        self,
        loader,
        max_sample_nodes: int = 50,
        max_depth: int = 5,
        seed: Optional[int] = None,
        graph_type: str = "citation",
        global_description: str = "",
    ) -> None:
        self.loader = loader
        self.max_sample_nodes = max_sample_nodes
        self.max_depth = max_depth
        self.seed = seed
        self.graph_type = graph_type
        self.global_description = global_description

    def sample(self) -> Optional[Dict[str, Any]]:
        """
        Sample representative graph context.
        
        Returns
        -------
        dict or None
            A dictionary containing readable node text, edge text, a subgraph summary, and a flag indicating whether textual attributes are available. Returns None when sampling fails.
        """
        try:
            # Sample seed nodes
            num_seeds = 5
            seed_infos = self.loader.sample_nodes(num_seeds, seed=self.seed)
            seed_ids = [info["node_id"] for info in seed_infos]

            # Extract a subgraph with DFS
            subgraph = self.loader.extract_subgraph(
                seed_node_ids=seed_ids,
                max_nodes=self.max_sample_nodes,
                max_depth=self.max_depth,
            )

            # Build edge text
            edge_text, id_to_name = self.loader.build_edge_text(subgraph)

            # Check whether raw_text exists (text graph)
            has_text = self._detect_has_text(subgraph)

            # Extract node text
            node_texts = self._extract_node_texts(subgraph, id_to_name)

            # Extract edge-relation text
            edge_texts = self._extract_edge_texts(subgraph, id_to_name)

            # Generate a subgraph summary
            subgraph_summary = self.loader.summarize_subgraph(subgraph, id_to_name=id_to_name)

            return {
                "node_texts": node_texts,
                "edge_texts": edge_texts,
                "subgraph_summary": subgraph_summary,
                "has_text": has_text,
                "num_nodes": subgraph["num_nodes"],
                "num_edges": subgraph["num_edges"],
            }

        except Exception as exc:
            logger.warning(f"GraphContextSampler.sample() failed: {exc}")
            return None

    def _detect_has_text(self, subgraph: Dict[str, Any]) -> bool:
        """Return whether graph nodes expose text attributes such as raw_text, raw_texts, abstract, or title."""
        for _, info in subgraph["nodes"].items():
            if info.get("raw_text") or info.get("raw_texts") or info.get("abstract") or info.get("title"):
                return True
        return False

    def _extract_node_texts(
        self, subgraph: Dict[str, Any], id_to_name: Dict[int, str]
    ) -> List[str]:
        """Serialize node metadata into one xxx-readable line per node, organized by hop."""
        if not subgraph.get("seed_nodes"):
            return []
            
        center_node = subgraph["seed_nodes"][0]
        adj = {}
        for src, dst in subgraph["edges"]:
            adj.setdefault(src, set()).add(dst)
            adj.setdefault(dst, set()).add(src)
            
        hops = {0: [center_node]}
        visited = {center_node}
        queue = [(center_node, 0)]
        
        while queue:
            curr, depth = queue.pop(0)
            if depth >= 5:
                continue
            for nxt in adj.get(curr, []):
                if nxt not in visited:
                    visited.add(nxt)
                    queue.append((nxt, depth + 1))
                    hops.setdefault(depth + 1, []).append(nxt)
                    
        def get_text(nid):
            info = subgraph["nodes"].get(nid, {})
            name = id_to_name.get(nid, f"Node_{nid}")
            parts = [f"[{name}]"]
            if info.get("title"):
                parts.append(f"title: {info['title'][:100]}")
            if info.get("label"):
                parts.append(f"type/label: {info['label']}")
            if info.get("year"):
                parts.append(f"year: {info['year']}")
            if info.get("abstract"):
                parts.append(f"abstract: {info['abstract'][:150]}")
            elif info.get("raw_text") or info.get("raw_texts"):
                text = info.get("raw_text") or info.get("raw_texts")
                parts.append(f"text: {str(text)[:150]}")
            return " | ".join(parts)

        lines = []
        lines.append(f"Center Node: {get_text(center_node)}")
        
        max_depth = max(hops.keys()) if hops else 0
        for depth in range(1, max_depth + 1):
            nodes_in_hop = hops.get(depth, [])
            if not nodes_in_hop:
                continue
            sampled = nodes_in_hop[:2]
            texts = [get_text(nid) for nid in sampled]
            lines.append(f"Hop {depth}: " + ", ".join(texts))
            
        return lines

    def _extract_edge_texts(
        self, subgraph: Dict[str, Any], id_to_name: Dict[int, str]
    ) -> List[str]:
        """Return the configured hard-coded edge description."""
        if self.graph_type == "social":
            return ["The edge represents a comment/follow relationship in a social network."]
        elif self.graph_type == "recommendation":
            return ["The edge represents a co-purchased/co-viewed relationship in a recommendation network."]
        elif self.graph_type == "citation":
            return ["The edge represents a cited relationship in a citation network."]
        else:
            if self.global_description:
                return [f"The edge represents a relationship based on this context: {self.global_description}"]
            else:
                return ["The edge represents a connection between entities."]


# ─────────────────────────────────────────────────────────────────────────────
# Task 1.5: xxx — dynamically generate a high-level graph summary
# ─────────────────────────────────────────────────────────────────────────────

_SUMMARY_SYSTEM_PROMPT = """\
You are an expert data analyst. Your task is to analyze a sampled subgraph from a larger dataset and determine its semantic structure and domain.
You will be provided with sampled node metadata and edge connections.
Based on this information, output a concise summary focusing ONLY on:
1. Node Types: What entities do the nodes represent? (e.g., academic papers, authors, products, users).
2. Edge Meaning: What does a directed/undirected edge represent in this context? (e.g., citation, co-purchase, authoring).
3. Overall Domain: What is the specific sub-domain or field of this dataset? (e.g., Diabetes Research, Machine Learning, Dietary Supplements).

Do NOT list specific node titles or IDs. Provide a high-level semantic summary.
"""

_SUMMARY_USER_PROMPT_TEMPLATE = """\
### Node Samples
{node_texts}

### Edge Samples
{edge_texts}

Please provide the graph summary based on the rules.
"""

class xxx:
    def __init__(self, xxx_provider, max_retries: int = 3):
        self.xxx = xxx_provider
        self.max_retries = max_retries

    async def generate(self, graph_context: Dict[str, Any]) -> str:
        node_text_block = "\n".join(f"  {t}" for t in (graph_context.get("node_texts") or [])[:15])
        edge_text_block = "\n".join(f"  {t}" for t in (graph_context.get("edge_texts") or [])[:20])
        
        user_prompt = _SUMMARY_USER_PROMPT_TEMPLATE.format(
            node_texts=node_text_block or "(no node texts)",
            edge_texts=edge_text_block or "(no edge texts)",
        )

        attempt = 1
        while True:
            try:
                raw = await self.xxx.get_completion(
                    system_prompt=_SUMMARY_SYSTEM_PROMPT,
                    user_prompt=user_prompt,
                    max_tokens=500,
                )
                if raw and raw.strip():
                    return raw.strip()
            except Exception as exc:
                logger.warning(f"xxx: generation attempt {attempt} failed: {exc}")
            attempt += 1


