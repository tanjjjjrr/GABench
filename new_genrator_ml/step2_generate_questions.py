def _load_step0_cache(cache_path: str) -> Dict:
    """Load dynamic_tool_descriptions, real_world_scenarios, and the TPG graph index from the global_metrics_cache.json file generated by step0."""
    empty = {"dynamic_tool_descriptions": {}, "real_world_scenarios": [], "tpg_graphs_index": {}}
    if not cache_path:
        return empty
    p = Path(cache_path)
    if not p.exists():
        logger.warning(f"The metrics-cache file does not exist: {cache_path}; using hard-coded descriptions")
        return empty
    try:
        with open(p, "r", encoding="utf-8") as f:
            cache = json.load(f)
        descs = cache.get("dynamic_tool_descriptions", {})
        scenarios = cache.get("real_world_scenarios", [])
        # TPG mode: build a fast index keyed by graph_idx
        tpg_graphs_list = cache.get("tpg_graphs", [])
        tpg_graphs_index = {str(g["graph_idx"]): g for g in tpg_graphs_list}
        logger.info(
            f"Loaded {len(descs)} dynamic tool descriptions, "
            f"{len(scenarios)} real-world scenarios, "
            f"{len(tpg_graphs_list)} cached TPG graphs"
        )
        return {
            "dynamic_tool_descriptions": descs,
            "real_world_scenarios": scenarios,
            "tpg_graphs_index": tpg_graphs_index,
        }
    except Exception as exc:
        logger.warning(f"Failed to read metrics-cache: {exc}; using hard-coded descriptions")
        return empty


